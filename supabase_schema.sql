-- 1. Habilitar extensão para geração de UUID se necessário
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 2. Limpeza prévia de tabelas anteriores (para aplicar o novo catálogo limpo)
DROP TABLE IF EXISTS public.avaliacoes CASCADE;
DROP TABLE IF EXISTS public.pedidos CASCADE;
DROP TABLE IF EXISTS public.produtos CASCADE;

-- 3. Tabela de PRODUTOS OFICIAIS
CREATE TABLE public.produtos (
    id INT PRIMARY KEY,
    titulo VARCHAR(255) NOT NULL,
    descricao TEXT,
    preco NUMERIC(10, 2) NOT NULL CHECK (preco >= 0),
    categoria VARCHAR(100) NOT NULL, -- 'Higiene e Cuidados', 'Equipamentos', 'Brinquedos', 'Alimentação'
    imagem TEXT NOT NULL,
    estoque INTEGER NOT NULL DEFAULT 10 CHECK (estoque >= 0),
    avaliacoes_count INTEGER NOT NULL DEFAULT 0,
    nota_media NUMERIC(3, 1) NOT NULL DEFAULT 5.0,
    criado_em TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 4. Tabela de AVALIAÇÕES (REVIEWS) DOS CLIENTES
CREATE TABLE public.avaliacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produto_id INT REFERENCES public.produtos(id) ON DELETE CASCADE,
    nome_cliente VARCHAR(100) NOT NULL,
    nota INT CHECK (nota >= 1 AND nota <= 5),
    comentario TEXT,
    criado_em TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 5. Tabela de PEDIDOS
CREATE TABLE public.pedidos (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    numero_pedido VARCHAR(50) UNIQUE NOT NULL,
    cliente_nome VARCHAR(255) NOT NULL,
    cliente_email VARCHAR(255) NOT NULL,
    cliente_cpf VARCHAR(20) NOT NULL,
    cliente_telefone VARCHAR(25),
    endereco JSONB NOT NULL,
    itens JSONB NOT NULL,
    subtotal NUMERIC(10, 2) NOT NULL,
    valor_frete NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    total NUMERIC(10, 2) NOT NULL,
    metodo_pagamento VARCHAR(50) NOT NULL,
    status_pagamento VARCHAR(50) NOT NULL DEFAULT 'pendente',
    payment_id VARCHAR(100),
    codigo_rastreio VARCHAR(100),
    criado_em TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 6. Índices para Otimização de Consultas
CREATE INDEX idx_produtos_categoria ON public.produtos (categoria);
CREATE INDEX idx_avaliacoes_produto_id ON public.avaliacoes (produto_id);
CREATE INDEX idx_pedidos_numero ON public.pedidos (numero_pedido);

-- 7. Configuração de RLS (Row Level Security)
ALTER TABLE public.produtos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.avaliacoes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.pedidos ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Produtos visíveis publicamente" 
ON public.produtos FOR SELECT 
USING (true);

CREATE POLICY "Avaliações visíveis publicamente" 
ON public.avaliacoes FOR SELECT 
USING (true);

CREATE POLICY "Qualquer cliente pode enviar avaliação" 
ON public.avaliacoes FOR INSERT 
WITH CHECK (true);

CREATE POLICY "Qualquer cliente pode criar pedido" 
ON public.pedidos FOR INSERT 
WITH CHECK (true);

CREATE POLICY "Leitura de pedidos" 
ON public.pedidos FOR SELECT 
USING (true);

